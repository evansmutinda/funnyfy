#!/usr/bin/env node
/* eslint-disable no-console */

/**
 * Build mobile comparison assets from full-size originals.
 *
 * Source (NOT bundled):  apps/mobile/assets/comparisons/source/before|after/**
 * Output (bundled):      apps/mobile/assets/comparisons/tiles/**  (~400px)
 *                        apps/mobile/assets/comparisons/hero/**   (~832px)
 *
 * Also regenerates:
 *   apps/mobile/data/comparisonPairAssets.generated.js
 *
 * Usage:
 *   node scripts/build-comparison-assets.js
 *   node scripts/build-comparison-assets.js --force
 */

const fs = require('fs/promises');
const path = require('path');
const sharp = require('sharp');

const ROOT = path.resolve(__dirname, '..');
const SOURCE_DIR = path.join(ROOT, 'apps/mobile/assets/comparisons/source');
const MOBILE_ASSETS = path.join(ROOT, 'apps/mobile/assets/comparisons');
const PAIRS_JS = path.join(ROOT, 'apps/mobile/data/comparisonPairs.js');
const GENERATED_JS = path.join(ROOT, 'apps/mobile/data/comparisonPairAssets.generated.js');
const CONSTANTS_JS = path.join(ROOT, 'apps/mobile/constants.js');

const TIERS = {
  tiles: { maxWidth: 400, quality: 80 },
  hero: { maxWidth: 832, maxHeight: 1248, quality: 85 },
};

const IMAGE_RE = /\.(jpe?g|png|webp)$/i;
const REQUIRE_RE = /require\('\.\.\/assets\/comparisons\/((?:before|after)\/[^']+)'\)/g;

const force = process.argv.includes('--force');

function toOutputRel(inputRel) {
  const parsed = path.posix.parse(inputRel.replace(/\\/g, '/'));
  return path.posix.join(parsed.dir, `${parsed.name}.jpg`);
}

async function walkImages(dir, base = dir) {
  const out = [];
  const entries = await fs.readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...await walkImages(full, base));
    } else if (IMAGE_RE.test(entry.name)) {
      out.push(path.relative(base, full).replace(/\\/g, '/'));
    }
  }
  return out;
}

async function shouldSkip(srcPath, destPath) {
  if (force) return false;
  try {
    const [srcStat, destStat] = await Promise.all([
      fs.stat(srcPath),
      fs.stat(destPath),
    ]);
    return destStat.mtimeMs >= srcStat.mtimeMs;
  } catch {
    return false;
  }
}

async function convertOne(srcPath, destPath, tierConfig) {
  await fs.mkdir(path.dirname(destPath), { recursive: true });
  let pipeline = sharp(srcPath).rotate();
  if (tierConfig.maxHeight) {
    pipeline = pipeline.resize({
      width: tierConfig.maxWidth,
      height: tierConfig.maxHeight,
      fit: 'inside',
      withoutEnlargement: true,
    });
  } else {
    pipeline = pipeline.resize({
      width: tierConfig.maxWidth,
      fit: 'inside',
      withoutEnlargement: true,
    });
  }
  await pipeline.jpeg({ quality: tierConfig.quality, mozjpeg: true }).toFile(destPath);
}

async function buildTier(relPath, tierName, tierConfig) {
  const srcPath = path.join(SOURCE_DIR, relPath);
  const outRel = toOutputRel(relPath);
  const destPath = path.join(MOBILE_ASSETS, tierName, outRel);
  if (await shouldSkip(srcPath, destPath)) {
    return { rel: outRel, skipped: true };
  }
  await convertOne(srcPath, destPath, tierConfig);
  return { rel: outRel, skipped: false };
}

function collectRequirePaths(source) {
  const paths = new Set();
  let match;
  while ((match = REQUIRE_RE.exec(source)) !== null) {
    paths.add(match[1].replace(/\\/g, '/'));
  }
  return [...paths];
}

function posixRequire(relFromData) {
  return `require('../assets/comparisons/${relFromData.replace(/\\/g, '/')}')`;
}

function generateAssetsModule(allOutputRels) {
  const sorted = [...allOutputRels].sort();
  const lines = [
    '// AUTO-GENERATED by scripts/build-comparison-assets.js — do not edit.',
    '',
    'export const COMPARISON_TILE_ASSETS = {',
  ];
  for (const rel of sorted) {
    const key = rel.replace(/\\/g, '/');
    lines.push(`  '${key}': ${posixRequire(`tiles/${key}`)},`);
  }
  lines.push('};', '', 'export const COMPARISON_HERO_ASSETS = {');
  for (const rel of sorted) {
    const key = rel.replace(/\\/g, '/');
    lines.push(`  '${key}': ${posixRequire(`hero/${key}`)},`);
  }
  lines.push('};', '');
  return `${lines.join('\n')}`;
}

/** Metro (Android) is case-sensitive — only emit paths that exist on disk. */
async function collectBundledRels() {
  const tileRels = await walkImages(path.join(MOBILE_ASSETS, 'tiles'));
  const heroDir = path.join(MOBILE_ASSETS, 'hero');
  const existing = [];
  for (const rel of tileRels) {
    try {
      await fs.access(path.join(heroDir, rel));
      existing.push(rel.replace(/\\/g, '/'));
    } catch {
      console.warn(`[warn] Tile without matching hero: ${rel}`);
    }
  }
  return existing;
}

function rewriteComparisonPairs(source, pathMap) {
  let next = source.replace(
    /\/\/ Layout:[\s\S]*?\/\/   assets\/comparisons\/after\/<categoryFolder>\/<after>\.jpg\|jpeg/,
    '// Layout:\n'
      + '//   assets/comparisons/source/before|after/  (originals — not bundled)\n'
      + '//   assets/comparisons/tiles/           (picker thumbnails)\n'
      + '//   assets/comparisons/hero/            (upload crossfade)',
  );

  if (!next.includes("from './comparisonPairAssets.generated'")) {
    next = next.replace(
      "import { getStyleImage } from '../constants';",
      "import { getStyleImage } from '../constants';\n"
        + "import { COMPARISON_HERO_ASSETS, COMPARISON_TILE_ASSETS } from './comparisonPairAssets.generated';",
    );
  }

  next = next.replace(
    /const CURATED_PAIR_PATHS = \{[\s\S]*?\n\};/,
    buildCuratedPairsBlock(pathMap),
  );

  next = next.replace(
    /export function getComparisonPair\(style\) \{[\s\S]*?\n\}/,
    `export function getComparisonPair(style, tier = 'hero') {
  if (!style) {
    return { before: DEFAULT_BEFORE, after: DEFAULT_BEFORE };
  }
  const curated = resolveCuratedPair(style.id, tier);
  if (curated) return curated;
  return {
    before: DEFAULT_BEFORE,
    after: getStyleImage(style),
  };
}

export function getTileComparisonPair(style) {
  return getComparisonPair(style, 'tiles');
}`,
  );

  if (!next.includes('function resolveCuratedPair')) {
    next = next.replace(
      'export function hasCuratedComparisonPair(style) {',
      `function assetForTier(relPath, tier) {
  const key = toOutputRel(relPath);
  const table = tier === 'tiles' ? COMPARISON_TILE_ASSETS : COMPARISON_HERO_ASSETS;
  return table[key] || null;
}

function resolveCuratedPair(styleId, tier) {
  const paths = CURATED_PAIR_PATHS[styleId];
  if (!paths) return null;
  const before = assetForTier(paths.before, tier);
  const after = assetForTier(paths.after, tier);
  if (!before || !after) return null;
  return { before, after };
}

function toOutputRel(inputRel) {
  const slash = inputRel.replace(/\\\\/g, '/');
  const last = slash.lastIndexOf('/');
  const dir = last >= 0 ? slash.slice(0, last) : '';
  const file = last >= 0 ? slash.slice(last + 1) : slash;
  const dot = file.lastIndexOf('.');
  const stem = dot >= 0 ? file.slice(0, dot) : file;
  return dir ? \`\${dir}/\${stem}.jpg\` : \`\${stem}.jpg\`;
}

export function hasCuratedComparisonPair(style) {`,
    );
  }

  next = next.replace('export { DEFAULT_BEFORE, CURATED_PAIRS };', 'export { DEFAULT_BEFORE, CURATED_PAIR_PATHS };');

  return next;
}

function buildCuratedPairsBlock(pathMap) {
  const lines = ['const CURATED_PAIR_PATHS = {'];
  for (const [styleId, paths] of Object.entries(pathMap)) {
    lines.push(`  '${styleId}': {`);
    lines.push(`    before: '${paths.before}',`);
    if (Array.isArray(paths.after)) {
      const listed = paths.after.map((a) => `'${a}'`).join(', ');
      lines.push(`    after: [${listed}],`);
    } else {
      lines.push(`    after: '${paths.after}',`);
    }
    lines.push('  },');
  }
  lines.push('};');
  return lines.join('\n');
}

function extractCuratedPathMap(pairsSource) {
  const pathsBlock = pairsSource.match(/const CURATED_PAIR_PATHS = \{([\s\S]*?)\n\};/);
  const legacyBlock = pairsSource.match(/const CURATED_PAIRS = \{([\s\S]*?)\n\};/);
  const block = pathsBlock || legacyBlock;
  if (!block) throw new Error('Could not parse curated pair paths from comparisonPairs.js');

  if (pathsBlock) {
    const map = {};
    const entryRe =
      /['"]?([\w-]+)['"]?\s*:\s*\{\s*before:\s*'([^']+)',\s*after:\s*(\[[\s\S]*?\]|'[^']+')\s*,?\s*\}/g;
    let match;
    while ((match = entryRe.exec(block[0])) !== null) {
      const afterRaw = match[3].trim();
      let after;
      if (afterRaw.startsWith('[')) {
        after = [...afterRaw.matchAll(/'([^']+)'/g)].map((m) => m[1]);
      } else {
        after = afterRaw.slice(1, -1);
      }
      map[match[1]] = { before: match[2], after };
    }
    if (Object.keys(map).length === 0) {
      throw new Error('No CURATED_PAIR_PATHS entries parsed');
    }
    return map;
  }

  const map = {};
  const entryRe = /['"]?([\w-]+)['"]?\s*:\s*\{[\s\S]*?before:\s*require\('\.\.\/assets\/comparisons\/([^']+)'\)[\s\S]*?after:\s*require\('\.\.\/assets\/comparisons\/([^']+)'\)/g;
  let match;
  while ((match = entryRe.exec(block[0])) !== null) {
    map[match[1]] = { before: match[2], after: match[3] };
  }
  if (Object.keys(map).length === 0) {
    throw new Error('No curated pairs parsed — check comparisonPairs.js format');
  }
  return map;
}

async function patchConstantsJs() {
  let source = await fs.readFile(CONSTANTS_JS, 'utf8');
  const next = source.replace(
    /\.\/assets\/comparisons\/after\//g,
    './assets/comparisons/tiles/after/',
  ).replace(
    /(\.\/assets\/comparisons\/tiles\/after\/[^']+\.)jpeg'/g,
    (m) => m.replace('.jpeg', '.jpg'),
  );
  if (next !== source) {
    await fs.writeFile(CONSTANTS_JS, next, 'utf8');
    console.log('[build-comparison-assets] Updated constants.js thumbnail paths → tiles/');
  }
}

async function main() {
  for (const sub of ['before', 'after']) {
    const p = path.join(SOURCE_DIR, sub);
    try {
      await fs.access(p);
    } catch {
      throw new Error(`Missing ${p}. Put originals under apps/mobile/assets/comparisons/source/before and .../after.`);
    }
  }

  const pairsSource = await fs.readFile(PAIRS_JS, 'utf8');
  const curatedPathMap = extractCuratedPathMap(pairsSource);
  const referenced = [
    ...collectRequirePaths(pairsSource),
    ...Object.values(curatedPathMap).flatMap((p) => [
      p.before,
      ...(Array.isArray(p.after) ? p.after : [p.after]),
    ]),
  ];
  const allSourceImages = await walkImages(SOURCE_DIR);
  const toConvert = [...new Set([...referenced, ...allSourceImages])];

  console.log(`[build-comparison-assets] Converting ${toConvert.length} source images…`);
  let converted = 0;
  let skipped = 0;

  for (const relPath of toConvert) {
    const srcPath = path.join(SOURCE_DIR, relPath);
    try {
      await fs.access(srcPath);
    } catch {
      console.warn(`[warn] Missing source file: ${relPath}`);
      continue;
    }

    for (const [tierName, tierConfig] of Object.entries(TIERS)) {
      const result = await buildTier(relPath, tierName, tierConfig);
      if (result.skipped) skipped += 1;
      else converted += 1;
    }
  }

  const bundledRels = await collectBundledRels();
  const generated = generateAssetsModule(bundledRels);
  await fs.writeFile(GENERATED_JS, generated, 'utf8');
  console.log(`[build-comparison-assets] Wrote ${path.relative(ROOT, GENERATED_JS)}`);

  const rewrittenPairs = rewriteComparisonPairs(pairsSource, curatedPathMap);
  await fs.writeFile(PAIRS_JS, rewrittenPairs, 'utf8');
  console.log('[build-comparison-assets] Updated comparisonPairs.js (tiles + hero tiers)');

  await patchConstantsJs();

  console.log(`[build-comparison-assets] Done — converted: ${converted}, skipped (up-to-date): ${skipped}`);
}

main().catch((err) => {
  console.error('[build-comparison-assets] Fatal:', err);
  process.exit(1);
});
